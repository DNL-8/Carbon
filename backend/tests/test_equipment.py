import json
import os
from pathlib import Path

import pytest

from app.equipment import DEFAULT_GEAR, gear_bonus, migrate_gear


def test_legacy_and_wrong_slot():
    assert migrate_gear({"helm": "hm-scout-hood", "weapon": "wp-wooden-blade"}) == DEFAULT_GEAR
    assert migrate_gear({"arma": "elmo_couro_novato"})["arma"] is None
    assert gear_bonus({})["bossDamageBonusPercent"] == 0


def test_typescript_equipment_oracle():
    path = os.environ.get("MURIM_EQUIPMENT_ORACLE")
    if not path:
        pytest.skip("TypeScript parity fixture is generated by CI")
    cases = json.loads(Path(path).read_text(encoding="utf-8"))
    assert len(cases) > 350
    for case in cases:
        assert migrate_gear(case["input"]) == case["migrated"]
        assert gear_bonus(case["input"]) == case["bonus"], case["input"]
