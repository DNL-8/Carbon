import json
import os
from pathlib import Path

import pytest

from app.rewards import evaluate_record, session_rewards


def test_rewards_oracle():
    path = os.environ.get("MURIM_REWARDS_ORACLE")
    if not path:
        pytest.skip("TypeScript parity fixture is generated by CI")
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    assert len(data["cases"]) > 100
    for c in data["cases"]:
        assert session_rewards(c["workout"], c["sets"], c["elapsed"], c["bonuses"], c["prs"]) == c["expected"]
    for c in data["records"]:
        assert list(evaluate_record(c["sets"], c["prev"])) == c["expected"]
