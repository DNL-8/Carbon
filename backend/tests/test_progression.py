import json
import os
from pathlib import Path

import pytest

from app.progression import (
    calculate_level,
    calculate_murim_qi,
    dual_progression,
    effective_streak,
    hunter_rank_progress,
    recalculate_progression,
)


@pytest.mark.parametrize("xp,level,qi", [
    (-1, 1, 0), (0, 1, 0), (1999, 1, 674), (2000, 2, 675),
    (4000, 3, 1350), (8500, 5, 2700), (13500, 8, 4100),
    (19000, 11, 5600), (25000, 15, 7200), (31500, 20, 8900),
    (38500, 25, 10800), (45500, 25, 12700),
])
def test_progression_boundaries(xp, level, qi):
    assert calculate_level(xp) == level
    assert calculate_murim_qi(xp) == qi


def test_streak_and_activity_qi():
    today = "2026-11-27"
    assert effective_streak(7, "2026-11-26", today) == 7
    assert effective_streak(7, "2026-11-25", today) == 0
    stats = {"totalXp": 0, "totalWorkouts": 10, "bossesDefeated": 2,
             "currentStreak": 7, "longestStreak": 7, "totalMinutes": 50,
             "lastWorkoutDate": "2026-11-26"}
    assert dual_progression(stats, today)["murim"]["qiPoints"] == 520
    stats["totalXp"] = 4000
    assert dual_progression(stats, today)["murim"]["qiPoints"] == 1350


def test_nonfinite_xp():
    for xp in (float("nan"), float("inf"), -float("inf")):
        assert recalculate_progression(xp) == recalculate_progression(0)


def test_typescript_progression_oracle():
    path = os.environ.get("MURIM_PROGRESSION_ORACLE")
    if not path:
        pytest.skip("TypeScript parity fixture is generated by CI")
    oracle = json.loads(Path(path).read_text(encoding="utf-8"))
    assert len(oracle["xp"]) > 400
    assert len(oracle["dual"]) > 1200
    for case in oracle["xp"]:
        assert recalculate_progression(case["input"]) == case["expected"], case["input"]
    for case in oracle["level"]:
        assert hunter_rank_progress(case["input"]) == case["expected"], case["input"]
    for case in oracle["dual"]:
        assert dual_progression(case["input"], case["today"]) == case["expected"], case["input"]
